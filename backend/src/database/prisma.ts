import { PrismaClient } from '@prisma/client';
import bcrypt from 'bcryptjs';
import { env } from '../config/env';

// Global Prisma Client instance
export const prisma = new PrismaClient();

// Flag to track whether PostgreSQL is connected
export let isPostgresConnected = false;

// In-Memory resilient fallback store in case local PostgreSQL is offline
export interface FallbackData {
  products: any[];
  orders: any[];
  orderItems: any[];
  coupons: any[];
  adminUsers: any[];
}

export const fallbackDb: FallbackData = {
  products: [],
  orders: [],
  orderItems: [],
  coupons: [],
  adminUsers: [],
};

// Check DB Connection and initialize
export async function initializeDatabase(): Promise<boolean> {
  try {
    await prisma.$connect();
    isPostgresConnected = true;
    console.log('✅ [Database] Successfully connected to PostgreSQL via Prisma ORM.');
    return true;
  } catch (error) {
    isPostgresConnected = false;
    console.warn('⚠️ [Database] Could not connect to PostgreSQL on specified DATABASE_URL.');
    console.warn('⚡ [Database] Activating resilient in-memory fallback engine for Optica Luxe demo mode.');
    await initFallbackData();
    return false;
  }
}

